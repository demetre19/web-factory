"""emit_tokens.py — TOKENS.json → global.css (Tailwind v4 shape).

The five layers, in order — the ONLY emission shape the gate
accepts (TK.*):

  1. @theme          primitives: colour ramps (neutral + brand +
                     semantic states), spacing, radius, fonts,
                     easing/duration, z-index
  2. :root           semantic layer: bg-*/text-*/border-*/action-*/
                     shadow-* — what components consume
  3. .dark           every semantic var overridden
  4. @theme inline   semantic names → Tailwind utilities
                     (color-canvas, ink-primary, line-default…)
  5. @custom-variant dark — the dark variant utilities consume

Components bind semantic names only — a raw hex or a primitive
var in a component is a TK.3 FAIL.

Usage: emit_tokens.py TOKENS.json > global.css
       emit_tokens.py --check file.css   (self-verify)
"""

import json
import re
import sys

# TOKENS color role → semantic css var name (the contract surface)
ROLE_SEMANTIC = {
    'bg': 'bg-canvas',
    'surface': 'bg-surface',
    'surface_elevated': 'bg-elevated',
    'border': 'border-default',
    'ink': 'text-primary',
    'ink_muted': 'text-secondary',
    'accent': 'action-primary',
    'accent_foreground': 'action-primary-ink',
    'inverse': 'bg-inverse',
}
# extra semantic vars every emission carries (derived, not optional)
DERIVED_SEMANTIC = {
    'text-muted': 'color-mix(in oklch, var(--text-secondary) 80%,'
                  ' var(--bg-canvas))',
    'text-inverse': 'var(--text-inverse-src)',
    'border-strong': 'color-mix(in oklch, var(--border-default)'
                     ' 130%, var(--text-primary))',
    'border-focus': 'var(--action-primary)',
    'bg-subtle': 'color-mix(in oklch, var(--bg-surface) 60%,'
                 ' var(--bg-canvas))',
    'action-primary-hover': 'color-mix(in oklch,'
                            ' var(--action-primary) 88%, black)',
    'shadow-card': ('0 1px 2px color-mix(in oklch,'
                    ' var(--shadow-ink, black) 6%, transparent),'
                    ' 0 2px 8px color-mix(in oklch,'
                    ' var(--shadow-ink, black) 5%, transparent)'),
    'shadow-pop': ('0 4px 16px color-mix(in oklch,'
                   ' var(--shadow-ink, black) 10%, transparent),'
                   ' 0 12px 40px color-mix(in oklch,'
                   ' var(--shadow-ink, black) 8%, transparent)'),
}
# Tailwind utility names the inline map publishes
UTILITY_MAP = {
    'bg-canvas': 'canvas', 'bg-surface': 'surface',
    'bg-elevated': 'elevated', 'bg-subtle': 'subtle',
    'bg-inverse': 'inverse',
    'text-primary': 'ink-primary', 'text-secondary': 'ink-secondary',
    'text-muted': 'ink-muted', 'text-inverse': 'ink-inverse',
    'border-default': 'line-default',
    'border-strong': 'line-strong', 'border-focus': 'line-focus',
    'action-primary': 'action-primary',
    'action-primary-hover': 'action-hover',
    'action-primary-ink': 'action-ink',
    'shadow-card': 'shadow-card', 'shadow-pop': 'shadow-pop',
}

TYPE_SCALE_STEPS = ('xs', 'sm', 'base', 'lg', 'xl', '2xl', '3xl')


def _type_sizes(base, ratio):
    """Major-third-ish scale around the knob base size."""
    out = {}
    idx = {'xs': -2, 'sm': -1, 'base': 0, 'lg': 1, 'xl': 2,
           '2xl': 3, '3xl': 5}
    for step, n in idx.items():
        out[step] = round(base * (ratio ** n), 2)
    return out


def _radius_map(personality):
    return {'p0': 0.0, 'p1': 0.125, 'p2': 0.25, 'p3': 0.5,
            'p4': 0.75, 'p5': 1.0}.get(str(personality), 0.5)


def emit(tokens):
    knobs = tokens.get('knobs') or {}
    color = tokens.get('color') or {}
    modes = color.get('modes') or {}
    light = (modes.get('light') or {}).get('roles') \
        or color.get('roles') or {}
    dark = (modes.get('dark') or {}).get('roles') or {}
    base_px = float(knobs.get('type.base', 16)) or 16
    ratio = float(knobs.get('type.ratio', 1.25)) or 1.25
    sizes = _type_sizes(base_px, ratio)
    rad = _radius_map(knobs.get('radius.personality'))
    L = []
    A = L.append
    A('/* generated by emit_tokens.py — TK.1 five-layer contract */')
    A('@tailwind base;')
    A('@tailwind components;')
    A('@tailwind utilities;')
    A('')
    # ---- 1. @theme primitives -------------------------------------
    A('@theme {')
    A('  /* neutral ramp — brand-tinted at knobs.color.neutral_tint */')
    for role, hexv in light.items():
        safe = re.sub(r'\W+', '-', role)
        A(f'  --primitive-neutral-{safe}: {hexv};')
    A('  /* semantic state ramp */')
    for st, v in (('success', '#2F7D4F'), ('warning', '#B57708'),
                  ('danger', '#C0392B'), ('info', '#2E6FBE')):
        A(f'  --primitive-state-{st}: {v};')
    A('  /* spacing — ACSS density scale */')
    for rung in ('xs', 's', 'm', 'l', 'xl', '2xl'):
        A(f'  --primitive-space-{rung}: var(--space-{rung});')
    for rung in ('s', 'm', 'l'):
        A(f'  --primitive-section-space-{rung}:'
          f' var(--section-space-{rung});')
    A(f'  --primitive-radius: {rad}rem;')
    # knobs.type.font_display/font_body carry the DNA display-face CSS
    # stack (dna_tokens._finish); a bare TOKENS.json falls back to
    # the system sans stack.
    _def_stack = ('ui-sans-serif, system-ui, -apple-system, '
                  '"Segoe UI", Roboto, Helvetica, Arial, sans-serif')
    _fd = str(knobs.get('type.font_display') or _def_stack)
    _fb = str(knobs.get('type.font_body') or _fd)
    # a stack stays one var VALUE — quoted, or the minifier splits it
    # on commas and the css pipeline can't recover.
    A(f"  --primitive-font-display: '{_fd}';")
    A(f"  --primitive-font-body: '{_fb}';")
    # grid.gutter names the gap rung; only real rungs bind.
    _gut = str(knobs.get('grid.gutter') or 'space-m')
    if _gut not in ('space-xs', 'space-s', 'space-m', 'space-l',
                    'space-xl', 'space-2xl'):
        _gut = 'space-m'
    A(f'  --primitive-gutter: var(--{_gut});')
    # width.inner_rung sizes the collection card floor; off-rung →
    # the 28rem canon the G.5 check names.
    _inner = str(knobs.get('width.inner_rung') or 'full')
    _gridmin = {'10': '16rem', '20': '18rem', '30': '20rem',
                '40': '24rem', '50': '26rem', '60': '28rem',
                '70': '32rem', '80': '36rem', '90': '40rem',
                'full': '28rem'}.get(_inner, '28rem')
    A(f'  --primitive-grid-min: {_gridmin};')
    # the fs scale is sequential idx -1..+5 around the knob base —
    # emitted per step so --fs-* stays a pure binding, never a copy.
    for n in (-1, 0, 1, 2, 3, 4, 5):
        _nm = f'neg{-n}' if n < 0 else str(n)
        A(f'  --primitive-text-{_nm}:'
          f' {round(base_px * ratio ** n, 2) / 16:.3f}rem;')
    for step in TYPE_SCALE_STEPS:
        A(f'  --primitive-text-{step}:'
          f' {sizes[step] / 16:.3f}rem;')
    A('  --primitive-leading-body: 1.6;')
    A('  --primitive-leading-display: 1.15;')
    A('  --primitive-ease: cubic-bezier(.2,.6,.2,1);')
    A('  --primitive-duration-fast: 150ms;')
    A('  --primitive-duration-med: 300ms;')
    A('  --primitive-z-base: 0;')
    A('  --primitive-z-sticky: 10;')
    A('  --primitive-z-overlay: 50;')
    A('}')
    A('')
    # ---- 2. :root semantic layer ----------------------------------
    A(':root {')
    A('  --text-inverse-src: #FFFFFF;')
    for role, var in ROLE_SEMANTIC.items():
        if role in light:
            A(f'  --{var}: {light[role]};')
    for name, val in DERIVED_SEMANTIC.items():
        A(f'  --{name}: {val};')
    A('}')
    A('')
    # ---- 3. .dark — every semantic overridden ---------------------
    A('.dark {')
    for role, var in ROLE_SEMANTIC.items():
        if role in dark:
            A(f'  --{var}: {dark[role]};')
        elif role in light:          # mirror — parity is the law
            A(f'  --{var}: {light[role]};')
    A('  --text-inverse-src: #0E1416;')
    A('  --shadow-ink: black;')
    A('  --shadow-card: 0 1px 2px color-mix(in oklch,'
      ' var(--shadow-ink) 35%, transparent), 0 2px 8px'
      ' color-mix(in oklch, var(--shadow-ink) 30%, transparent);')
    A('  --shadow-pop: 0 4px 16px color-mix(in oklch,'
      ' var(--shadow-ink) 45%, transparent), 0 12px 40px'
      ' color-mix(in oklch, var(--shadow-ink) 35%, transparent);')
    # derived semantics re-declare so their mix() resolves against
    # the dark bases — TK.2 parity covers every semantic var
    for name, val in DERIVED_SEMANTIC.items():
        if name in ('shadow-card', 'shadow-pop'):
            continue
        A(f'  --{name}: {val};')
    A('}')
    A('')
    # ---- 4. @theme inline — semantic → utilities ------------------
    A('@theme inline {')
    for var, util in UTILITY_MAP.items():
        A(f'  --color-{util}: var(--{var});')
    A('}')
    A('')
    # ---- 5. dark variant -------------------------------------------
    A('@custom-variant dark (&:where(.dark, .dark *));')
    return '\n'.join(L) + '\n'


def main(argv):
    if len(argv) >= 2 and argv[1] == '--check':
        css = open(argv[2], encoding='utf-8').read()
        need = ['@theme {', ':root {', '.dark {',
                '@theme inline {', '@custom-variant dark']
        miss = [x for x in need if x not in css]
        print('layers missing:', miss if miss else 'none')
        return 0 if not miss else 1
    tokens = json.load(open(argv[1], encoding='utf-8'))
    sys.stdout.write(emit(tokens))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
