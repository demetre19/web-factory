#!/usr/bin/env python3
"""checklist_emit.py — CHECKLIST/<wave>.md producer (P.9, U.5).

Every wave's evidence table is generated, never hand-written. Rows come
from the producer receipts pipeline.py records under .receipts/: one row
per producer step (tool, command, input sha256s, output sha256s) plus one
row per WAVE_INPUTS file citing the receipt that produced it — so every
gate input is traceable to a tool step.

  python3 checklist_emit.py <pipeline-or-site-dir> <wave>

Receipt shape (written by pipeline.py):
  .receipts/<wave>.json
  {"steps": [{"label", "argv", "inputs":  {relpath: sha16},
              "outputs": {relpath: sha16}, "rc", "ts"}]}
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gate as G  # noqa: E402


def _sha16(path):
    import hashlib
    try:
        with open(path, 'rb') as fh:
            return hashlib.sha256(fh.read()).hexdigest()[:16]
    except OSError:
        return None


def _cell(s):
    return str(s).replace('|', '/').replace('\n', ' ')


def _receipt_dir(d):
    return os.path.join(d, '.receipts')


def _load(d, wave):
    p = os.path.join(_receipt_dir(d), wave + '.json')
    if not os.path.isfile(p):
        return []
    try:
        return (json.load(open(p)) or {}).get('steps') or []
    except Exception:
        return []


def _resolve(d, rel):
    """Page dirs resolve site-scoped inputs to the site folder (same
    rule as gate.Ctx._path / SITE_SCOPED)."""
    p = os.path.join(d, rel)
    if os.path.isfile(p):
        return p
    up = os.path.dirname(os.path.dirname(d))
    if os.path.basename(os.path.dirname(d)) == 'pages':
        cand = os.path.join(up, rel)
        if os.path.isfile(cand):
            return cand
    return p


def _producer_of(d, upto_wave, relpath, cur=None):
    """Receipted step that wrote relpath — searched across EVERY wave,
    not only waves ≤ this one: a later producer legitimately rewrites
    an earlier wave's input (w3 projects the pick into DESIGN-PLAN.md,
    w4 rewrites its options block), and the row must cite the step
    whose recorded sha matches the file the gate resolves. Page dirs
    also scan the site dir's receipts — the s0 wave owns site-scoped
    files (site DNA/TOKENS at s0, page-scoped copies at w0). With no
    sha match, the newest step wins so the row honestly reports
    CHANGED."""
    order = ['s0'] + G.WAVE_SEQ
    waves = order
    dirs = [d]
    up = os.path.dirname(os.path.dirname(d))
    if os.path.basename(os.path.dirname(d)) == 'pages' and up != d:
        dirs.append(up)
    hits = []
    for dd in reversed(dirs):           # site first: page hits win ties
        for w in waves:
            for st in _load(dd, w):
                if relpath in (st.get('outputs') or {}):
                    hits.append((w, st))
    for w, st in reversed(hits):
        if cur is not None and st['outputs'][relpath] == cur:
            return (w, st)
    return hits[-1] if hits else None


def emit(d, wave):
    steps = _load(d, wave)
    lines = ['| Rule | Evidence |', '|---|---|']
    for st in steps:
        argv = ' '.join(st.get('argv') or [])
        ins = st.get('inputs') or {}
        outs = st.get('outputs') or {}
        in_s = ', '.join(f'{k} sha256:{v}' for k, v in
                         sorted(ins.items())) or '—'
        out_s = ', '.join(f'{k} sha256:{v}' for k, v in
                          sorted(outs.items())) or '—'
        rc = st.get('rc')
        lines.append(
            f'| {_cell(st.get("label") or argv)} | '
            f'tool `{_cell(argv)}` exit {rc} — in: {_cell(in_s)} '
            f'→ out: {_cell(out_s)} |')
    # every gate input (gate.WAVE_INPUTS) cites the receipt that
    # produced it — a file no tool wrote is called out, not hidden
    for rel in G.WAVE_INPUTS.get(wave, []):
        cur = _sha16(_resolve(d, rel))
        hit = _producer_of(d, wave, rel, cur)
        if hit:
            w, st = hit
            lines.append(
                f'| input {rel} | produced by `{_cell(st.get("label"))}`'
                f' at {w} — sha256:{st["outputs"][rel]}'
                + ('' if st['outputs'][rel] == cur else
                   f' (now {cur} — CHANGED)') + ' |')
        else:
            lines.append(
                f'| input {rel} | no producer receipt — '
                f'{"present sha256:" + str(cur) if cur else "ABSENT"} '
                '(operator source or missing) |')
    if not steps and not G.WAVE_INPUTS.get(wave):
        lines.append('| no producers | wave has no tool steps '
                     '(gate-only stage) |')
    out = os.path.join(d, 'CHECKLIST', wave + '.md')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    txt = ('<!-- GENERATED by checklist_emit.py from .receipts/ '
           '— do not edit -->\n' + '\n'.join(lines) + '\n')
    with open(out, 'w', encoding='utf-8') as fh:
        fh.write(txt)
    return out, txt


def main(argv):
    if len(argv) != 3:
        print('usage: checklist_emit.py <dir> <wave>')
        return 2
    out, _ = emit(os.path.abspath(argv[1]), argv[2])
    print(f'checklist → {out}')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
