#!/usr/bin/env python3
"""assemble.py — mechanical glue (SB.4).

Writes site/src/pages/<slug>.astro from DESIGN-PLAN section order:
imports every section component, wraps each in <Section> with the plan's
surface, density, wf_ref, media ratio and disclosure. Deterministic: the
page is never hand-edited; `gate.py w7` compares the file to this output.

Usage: python3 tools/design-gate/assemble.py <pipeline-dir> [--variants | --layouts]

--variants regenerates the picker (preview/variants.html): full
responsive page mockups per knob vector — actual designs, not style
sheets. It is the ONLY legal producer of the picker (VG.1).
--fine regenerates the fine round (preview/fine.html): three ±1-step
stylistic-knob nudges of the w4-approved design (P.18).

The default run also writes ASSEMBLED.md + SPEC.md at the pipeline
root — the w7 receipts bound in GATES.json (P.17).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gate
import preview_build


def main(argv):
    args = [a for a in argv[1:] if not a.startswith('--')]
    flags = {a for a in argv[1:] if a.startswith('--')}
    if not args or flags - {'--variants', '--layouts', '--fine',
                            '--candidates', '--system'}:
        print('usage: assemble.py <pipeline-dir> '
              '[--variants | --fine | --layouts | --candidates '
              '| --system]')
        return 2
    ctx = gate.Ctx(args[0])
    if '--system' in flags:
        # W5 system sheet — the REAL built tile (site/dist/preview/
        # system/index.html) shelled under preview/system.html
        path, txt, h = preview_build.emit_system(ctx)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w', encoding='utf-8') as fh:
            fh.write(txt)
        print(f'assembled system sheet → '
              f'{os.path.relpath(path, ctx.dir)} (marker {h})')
        return 0
    if '--layouts' in flags:
        path, txt, h = preview_build.emit_layouts(ctx)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w', encoding='utf-8') as fh:
            fh.write(txt)
        print(f'assembled layout picker → '
              f'{os.path.relpath(path, ctx.dir)} (marker {h})')
        return 0
    if '--variants' in flags:
        path, txt, h = preview_build.emit_variants(ctx)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w', encoding='utf-8') as fh:
            fh.write(txt)
        print(f'assembled picker → {os.path.relpath(path, ctx.dir)} '
              f'(marker {h})')
        return 0
    if '--candidates' in flags:
        path, txt, h = gate.assemble_candidates(ctx)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w', encoding='utf-8') as fh:
            fh.write(txt)
        print(f'assembled candidates → '
              f'{os.path.relpath(path, ctx.dir)} (marker {h})')
        return 0
    if '--fine' in flags:
        path, txt, h = gate.assemble_fine(ctx)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w', encoding='utf-8') as fh:
            fh.write(txt)
        print(f'assembled fine round → {os.path.relpath(path, ctx.dir)} '
              f'(marker {h})')
        return 0
    wrote = []
    for slug in (ctx.pages() or {'index': {}}):
        path, txt, h = gate.assemble_page(ctx, slug)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w', encoding='utf-8') as fh:
            fh.write(txt)
        wrote.append(f'{os.path.relpath(path, ctx.dir)} (marker {h})')
        sp = os.path.join(ctx.dir, 'PAGES', slug, 'SPEC.md')
        os.makedirs(os.path.dirname(sp), exist_ok=True)
        with open(sp, 'w', encoding='utf-8') as fh:
            fh.write(gate.assemble_spec(ctx, slug))
        wrote.append(os.path.relpath(sp, ctx.dir))
    # w7 receipts (ARTIFACTS): a root SPEC.md rolling every page spec up,
    # and ASSEMBLED.md — the pipeline-level assembly receipt.
    index = '# SPEC — all pages (generated by assemble.py; never edit)\n\n'
    for slug in (ctx.pages() or {'index': {}}):
        index += f'- [{slug}](PAGES/{slug}/SPEC.md)\n'
    with open(os.path.join(ctx.dir, 'SPEC.md'), 'w',
              encoding='utf-8') as fh:
        fh.write(index)
    wrote.append('SPEC.md')
    asm = ('# ASSEMBLED — assembly receipt '
           '(generated by assemble.py; never edit)\n\n'
           + '\n'.join(f'- {w}' for w in wrote) + '\n')
    with open(os.path.join(ctx.dir, 'ASSEMBLED.md'), 'w',
              encoding='utf-8') as fh:
        fh.write(asm)
    wrote.append('ASSEMBLED.md')
    print('assembled ' + ', '.join(wrote))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
